'use strict';

/**
 * SCMAdapter
 * Unified Source Code Management adapter for Git, GitHub, GitLab, and Bitbucket repositories.
 */
class SCMAdapter {
    /**
     * @param {Object} config
     * @param {string} [config.provider='github'] - Driver type: 'git', 'github', 'gitlab', 'bitbucket'
     * @param {string} [config.repositoryUrl] - Repository remote URL or 'owner/repo'
     * @param {string} [config.branch='main'] - Target default branch
     * @param {string} [config.token] - Access Token / Personal Access Token
     * @param {string} [config.apiEndpoint] - Enterprise SCM API Endpoint base
     */
    constructor(config = {}) {
        this.provider = (config.provider || 'github').toLowerCase();
        this.repositoryUrl = config.repositoryUrl || 'ujomor-platform/eaorcs-core';
        this.branch = config.branch || 'main';
        this.token = config.token || 'mock_scm_token';
        this.apiEndpoint = config.apiEndpoint || this._getDefaultApiEndpoint();

        this._validateProvider();
    }

    _validateProvider() {
        const supported = ['git', 'github', 'gitlab', 'bitbucket'];
        if (!supported.includes(this.provider)) {
            throw new Error(`[SCMAdapter] Unsupported provider '${this.provider}'. Supported: ${supported.join(', ')}`);
        }
    }

    getProviderName() {
        return this.provider;
    }

    /**
     * Clone or fetch/sync repository into target local directory
     * @param {string} targetDir 
     * @returns {Promise<Object>} Sync result status
     */
    async cloneOrSync(targetDir = './repo_cache') {
        return {
            success: true,
            provider: this.provider,
            repository: this.repositoryUrl,
            branch: this.branch,
            targetDir,
            syncedAt: new Date().toISOString(),
            headCommit: `commit_${Math.random().toString(16).substring(2, 10)}`
        };
    }

    /**
     * Fetch recent commit history log
     * @param {number} [limit=10] 
     * @returns {Promise<Array<Object>>} List of commits
     */
    async fetchCommitHistory(limit = 10) {
        const commits = [];
        const now = Date.now();

        for (let i = 0; i < limit; i++) {
            commits.push({
                hash: `c${(now - i * 3600000).toString(16).substring(0, 7)}`,
                author: 'Enterprise Systems Lead <engineering@ujomor.com>',
                message: i === 0 ? 'feat(engine): stream 2 provider abstraction and branding engine' : `fix(core): automated governance policy pack sync #${i}`,
                timestamp: new Date(now - i * 3600000).toISOString(),
                branch: this.branch,
                provider: this.provider
            });
        }

        return commits;
    }

    /**
     * Create Pull Request / Merge Request across GitHub, GitLab, or Bitbucket
     * @param {Object} prData - { title, body, sourceBranch, targetBranch }
     * @returns {Promise<Object>} Pull Request details
     */
    async createPullRequest(prData = {}) {
        if (!prData.title || !prData.sourceBranch) {
            throw new Error('[SCMAdapter] Title and sourceBranch are required to create a PR/MR.');
        }

        const prId = Math.floor(100 + Math.random() * 900);
        const targetBranch = prData.targetBranch || this.branch;

        return {
            success: true,
            provider: this.provider,
            prId: prId,
            number: prId,
            title: prData.title,
            body: prData.body || 'Automated policy pull request generated by EAORCS Engine.',
            sourceBranch: prData.sourceBranch,
            targetBranch: targetBranch,
            status: 'OPEN',
            url: this._getPrUrl(prId),
            createdAt: new Date().toISOString()
        };
    }

    /**
     * Retrieve single file content from specified git ref/branch
     * @param {string} filePath 
     * @param {string} [ref] 
     * @returns {Promise<Object>} File content response
     */
    async getFileContent(filePath, ref = null) {
        if (!filePath) throw new Error('[SCMAdapter] File path is required.');

        const targetRef = ref || this.branch;
        const mockContent = `// SCM File Mock: ${filePath} @ ${targetRef}\nmodule.exports = { path: "${filePath}", ref: "${targetRef}" };`;

        return {
            path: filePath,
            ref: targetRef,
            repository: this.repositoryUrl,
            provider: this.provider,
            content: mockContent,
            encoding: 'utf-8',
            size: Buffer.byteLength(mockContent)
        };
    }

    /**
     * List remote branches in repository
     * @returns {Promise<Array<string>>} Branch names
     */
    async listBranches() {
        return [
            this.branch,
            'feature/stream-2-branding',
            'release/2026.1-LTS',
            'governance/policy-sync'
        ];
    }

    _getDefaultApiEndpoint() {
        switch (this.provider) {
            case 'github':
                return 'https://api.github.com';
            case 'gitlab':
                return 'https://gitlab.com/api/v4';
            case 'bitbucket':
                return 'https://api.bitbucket.org/2.0';
            case 'git':
            default:
                return 'https://git.enterprise.local/api';
        }
    }

    _getPrUrl(prId) {
        switch (this.provider) {
            case 'gitlab':
                return `https://gitlab.com/${this.repositoryUrl}/-/merge_requests/${prId}`;
            case 'bitbucket':
                return `https://bitbucket.org/${this.repositoryUrl}/pull-requests/${prId}`;
            case 'github':
            default:
                return `https://github.com/${this.repositoryUrl}/pull/${prId}`;
        }
    }
}

module.exports = SCMAdapter;
